"""D86 M0-04B: distill armour slot models (chest/hands/feet/shoulder) from the item_icon_id sweep.

Alpha names its armour models by slot and tier: ``iron-chest1..4`` and ``iron|silk|linen|wool-chest5``
(the sweep selectors confirm b0c 0..3 -> iron tiers and b0c 4..7 -> the four level-5 material families,
material 0/25/26/27 respectively). This script verifies those names exist among the models the sweep
selected and writes the type/subtype -> model table used by AlphaEquipmentLayer.

    python -m tools.alpha_content.build_equipment_models --raw .scratch/tmp/item_models_full.json
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_JSON = ROOT / "tools/alpha_content/data/equipment_models.json"
OUT_CS = ROOT / "Assets/CubeGame/Content/Generated/AlphaEquipmentModels.g.cs"
SELECTOR_VA = "0x004EC400"
SLOTS = {4: "chest", 5: "hand", 6: "foot", 7: "shoulder"}
FAMILIES = ["iron", "silk", "linen", "wool"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--raw", default=str(ROOT / ".scratch/tmp/item_models_full.json"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    raw = Path(a.raw)
    if not raw.exists():
        print("EQUIPMENT_MODELS=FAIL raw sweep missing " + str(raw))
        return 1
    sweep = json.loads(raw.read_text(encoding="utf-8"))
    names = {m.get("name") for m in sweep["models"].values() if m.get("name")}
    rows, missing = [], []
    for item_type, slot in SLOTS.items():
        for subtype in range(8):
            if subtype < 4:
                model = f"iron-{slot}{subtype + 1}.cub"
            else:
                model = f"{FAMILIES[subtype - 4]}-{slot}5.cub"
            if model not in names:
                missing.append(model)
                continue
            rows.append({"type": item_type, "subtype": subtype, "slot": slot, "model": model})
    if missing:
        print("EQUIPMENT_MODELS=FAIL missing " + ",".join(missing))
        return 1
    payload = {
        "format": "cubegame.equipment_models/1",
        "status": "EMULATED_ALPHA_CODE: models selected by executing item_icon_id; slot laws from item_layer evidence",
        "source": {"selector": SELECTOR_VA, "tool": "tools/alpha_models/catalog/item_models.py",
                   "sweep_models": len(names),
                   "note": "names encode slot+tier; selectors confirm b0c 0..3/4..7 families"},
        "items": rows,
    }
    text = json.dumps(payload, indent=1, ensure_ascii=True) + "\n"
    if a.check:
        ok = OUT_JSON.exists() and OUT_JSON.read_text(encoding="utf-8") == text
        print(("EQUIPMENT_MODELS=PASS" if ok else "EQUIPMENT_MODELS=FAIL drift") + f" items={len(rows)}")
        return 0 if ok else 1
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(text, encoding="utf-8", newline="\n")
    lines = [
        "// <auto-generated>",
        "// Generated by tools/alpha_content/build_equipment_models.py from the executed",
        f"// item_icon_id ({SELECTOR_VA}) sweep (armour names encode slot+tier).",
        f"// items={len(rows)}", "// </auto-generated>",
        "namespace CubeGame.Content", "{",
        "    public readonly struct AlphaEquipmentDef",
        "    {",
        "        public readonly int Type, Subtype; public readonly string Slot, Model;",
        "        public AlphaEquipmentDef(int type, int subtype, string slot, string model)",
        "        { Type = type; Subtype = subtype; Slot = slot; Model = model; }",
        "    }",
        "",
        "    public static class AlphaEquipmentModels",
        "    {",
        f'        public const string Selector = "{SELECTOR_VA}";',
        "        public static readonly AlphaEquipmentDef[] Items =",
        "        {",
    ]
    for r in rows:
        lines.append(f'            new AlphaEquipmentDef({r["type"]}, {r["subtype"]}, "{r["slot"]}", "{r["model"]}"),')
    lines += ["        };", "    }", "}"]
    OUT_CS.parent.mkdir(parents=True, exist_ok=True)
    OUT_CS.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"EQUIPMENT_MODELS=PASS items={len(rows)} out={OUT_CS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
