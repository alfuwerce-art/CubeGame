"""D1 REVIEW-FIX: the records executed from Cube.exe 0x5C9B30 / 0x5CA0A0 are VENDOR STOCK, not spawn rows.

History: this script was written as "turn the executed spawn descriptors into the spawn table" and read the
captured 0x118-byte records as (kind, weight, level). The review-fix established what they are:

  * the record is Alpha's ITEM structure (0x118 bytes): +0 item type, +1 subtype, +4 modifier (a random
    value, NOT a probability weight), +0xC rarity, +0xD material, +0x10 level;
  * 0x5C9B30 is called right after a template gets NPC class 0x80 (Cube.exe 0x5BCE42/0x5BCE53) and 0x5CA0A0
    after class 0x81 and 0x83 (0x5BD1FA/0x5BD20B, 0x5BD3D6/0x5BD3E7) — the lists are what those NPCs sell;
  * type 2 = formula, type 3 = weapon (subtype = weapon subtype), 1/11/20/23/24 = other items.

So the generated rows keep their old names for source compatibility (Level = item level, Kind = item
SUBTYPE, Weight = item modifier), they are still records produced by executed Alpha code, but they say
nothing about creatures. Summing the modifier over five seeds — which this aggregation does — has no Alpha
meaning; nothing in the game reads the rows after the review-fix.

    python -m tools.alpha_content.build_spawn_table            # write
    python -m tools.alpha_content.build_spawn_table --check    # verify no drift
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / "tools/alpha_content/data/spawn_descriptors.json"
OUTPUT = ROOT / "Assets/CubeGame/Content/Generated/AlphaSpawnTable.g.cs"
TYPE_MONSTER = 2
TYPE_NPC = 3


def aggregate(doc: dict) -> dict:
    buckets = {"monster": {}, "npc": {}}
    counts = {"monster": 0, "npc": 0}
    seeds = []
    for entry in doc["seeds"]:
        seeds.append(entry["seed"])
        for rec in entry["records"]:
            source = "monster" if rec["type"] == TYPE_MONSTER else "npc" if rec["type"] == TYPE_NPC else None
            if source is None:
                continue
            level = rec["level16"]
            kind = rec["kind"]
            if level <= 0 or kind < 0:
                continue
            key = (level, kind)
            buckets[source][key] = buckets[source].get(key, 0) + max(1, rec["weight"])
            counts[source] += 1
    rows = {}
    for source, bucket in buckets.items():
        rows[source] = sorted(({"level": lv, "kind": kd, "weight": w} for (lv, kd), w in bucket.items()),
                              key=lambda r: (r["level"], -r["weight"], r["kind"]))
    return {"seeds": seeds, "counts": counts, "rows": rows}


def build(doc: dict) -> str:
    agg = aggregate(doc)
    seeds = ", ".join(str(s) for s in agg["seeds"])

    def table(name: str, rows: list) -> str:
        body = "\n".join(f"            new AlphaSpawnEntryDef({r['level']}, 0x{r['kind']:02X}, {r['weight']}),"
                         for r in rows)
        return (f"        public static readonly AlphaSpawnEntryDef[] {name} =\n        {{\n{body}\n        }};\n")

    mon = agg["rows"]["monster"]
    npc = agg["rows"]["npc"]
    max_level = max([r["level"] for r in mon + npc] + [1])
    kinds = sorted({r["kind"] for r in mon + npc})
    return f"""// <auto-generated>
//   cubegame.alpha_spawn_table/1 (VENDOR ITEM records, not creature spawns) — generated by tools/alpha_content/build_spawn_table.py
//   source: Cube.exe 0x5C9B30 World_generateMonsterSpawnList / 0x5CA0A0 World_generateNpcSpawnList,
//           executed by tools/alpha_models/world/spawn_oracle.py (EMULATED_ALPHA_CODE)
//   world seeds: {seeds}
//   records: monster {agg['counts']['monster']}, npc {agg['counts']['npc']}
//   DO NOT EDIT: regenerate with `python -m tools.alpha_content.build_spawn_table`
// </auto-generated>
namespace CubeGame.Content
{{
    /// <summary>One aggregated vendor ITEM row (old spawn-table names kept): Level = item level, Kind = item subtype, Weight = summed item modifier (not a probability).</summary>
    public readonly struct AlphaSpawnEntryDef
    {{
        public readonly int Level;
        public readonly int Kind;
        public readonly int Weight;

        public AlphaSpawnEntryDef(int level, int kind, int weight)
        {{
            Level = level;
            Kind = kind;
            Weight = weight;
        }}
    }}

    /// <summary>NOT a creature spawn table: vendor stock item records of NPC classes 0x80 / 0x81 / 0x83 (see Status).</summary>
    public static class AlphaSpawnTable
    {{
        public const string Format = "cubegame.alpha_spawn_table/1";
        public const string Status = "EMULATED_ALPHA_CODE records of VENDOR ITEMS (classes 0x80/0x81/0x83); not creature kinds, Weight is not a probability; unused by population";
        public const string Source = "Cube.exe 0x5C9B30 / 0x5CA0A0 via tools/alpha_models/world/spawn_oracle.py";
        public const string Seeds = "{seeds}";

        /// <summary>Highest level row the executed tables contain.</summary>
        public const int MaxLevel = {max_level};

        /// <summary>Item type 2 (formula) records of the class 0x80 list (0x5C9B30); Kind = formula subtype.</summary>
{table('Monster', mon)}
        /// <summary>Item type 3 (weapon) records of the class 0x81/0x83 list (0x5CA0A0); Kind = weapon subtype.</summary>
{table('Npc', npc)}
        /// <summary>All item subtypes the records contain (NOT creature kind ids).</summary>
        public static readonly int[] Kinds = {{ {', '.join(f'0x{k:02X}' for k in kinds)} }};

        /// <summary>The +0xC byte is the item rarity in both lists.</summary>
        public const string MonsterStarsStatus = "WITHDRAWN: +0xC is item rarity; these are not monster records";
    }}
}}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", default=str(INPUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    doc = json.loads(Path(a.input).read_text(encoding="utf-8"))
    if doc.get("RESULT") != "PASS":
        print(f"SPAWN_TABLE_RESULT=FAIL source RESULT={doc.get('RESULT')} problems={doc.get('problems')}")
        return 1
    text = build(doc)
    if a.check:
        drift = not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text
        print(f"SPAWN_TABLE_RESULT={'FAIL' if drift else 'PASS'} drift={drift} out={OUTPUT}")
        return 1 if drift else 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    agg = aggregate(doc)
    print(f"SPAWN_TABLE_RESULT=PASS monster_rows={len(agg['rows']['monster'])} npc_rows={len(agg['rows']['npc'])} "
          f"records={agg['counts']} out={OUTPUT.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
