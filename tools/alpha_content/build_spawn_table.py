"""M0-06B / D1: turn the executed spawn descriptors into the committed C# spawn table.

Input:  ``tools/alpha_content/data/spawn_descriptors.json`` — records captured by executing Alpha's own
        ``World_generateMonsterSpawnList`` (0x5C9B30) and ``World_generateNpcSpawnList`` (0x5CA0A0) with
        ``tools/alpha_models/world/spawn_oracle.py`` for several world seeds (EMULATED_ALPHA_CODE).
Output: ``Assets/CubeGame/Content/Generated/AlphaSpawnTable.g.cs`` — weighted (level, kind) rows.

Field meaning used here (proven by correlating every builder call with the record it produced):
  type 2 record  = monster spawn descriptor   -> kind +1, weight +4, level +0x10 (builder argument)
  type 3 record  = NPC spawn descriptor       -> kind +1, weight +4, level +0x10, stars +0xC
The monster record's +0xC byte is NOT a star count (it is ~50/50 over all seeds, while the NPC record of
the same builder family shows the documented ~1 %), so stars stay 0 for monsters — recorded as PARTIAL.

    python -m tools.alpha_content.build_spawn_table            # write
    python -m tools.alpha_content.build_spawn_table --check    # verify no drift
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / "tools/alpha_content/data/spawn_descriptors.json"
OUTPUT = ROOT / "Assets/CubeGame/Content/Generated/AlphaSpawnTable.g.cs"
TYPE_MONSTER = 2
TYPE_NPC = 3


def aggregate(doc: dict) -> dict:
    buckets = {"monster": {}, "npc": {}}
    counts = {"monster": 0, "npc": 0}
    seeds = []
    for entry in doc["seeds"]:
        seeds.append(entry["seed"])
        for rec in entry["records"]:
            source = "monster" if rec["type"] == TYPE_MONSTER else "npc" if rec["type"] == TYPE_NPC else None
            if source is None:
                continue
            level = rec["level16"]
            kind = rec["kind"]
            if level <= 0 or kind < 0:
                continue
            key = (level, kind)
            buckets[source][key] = buckets[source].get(key, 0) + max(1, rec["weight"])
            counts[source] += 1
    rows = {}
    for source, bucket in buckets.items():
        rows[source] = sorted(({"level": lv, "kind": kd, "weight": w} for (lv, kd), w in bucket.items()),
                              key=lambda r: (r["level"], -r["weight"], r["kind"]))
    return {"seeds": seeds, "counts": counts, "rows": rows}


def build(doc: dict) -> str:
    agg = aggregate(doc)
    seeds = ", ".join(str(s) for s in agg["seeds"])

    def table(name: str, rows: list) -> str:
        body = "\n".join(f"            new AlphaSpawnEntryDef({r['level']}, 0x{r['kind']:02X}, {r['weight']}),"
                         for r in rows)
        return (f"        public static readonly AlphaSpawnEntryDef[] {name} =\n        {{\n{body}\n        }};\n")

    mon = agg["rows"]["monster"]
    npc = agg["rows"]["npc"]
    max_level = max([r["level"] for r in mon + npc] + [1])
    kinds = sorted({r["kind"] for r in mon + npc})
    return f"""// <auto-generated>
//   cubegame.alpha_spawn_table/1 — generated by tools/alpha_content/build_spawn_table.py
//   source: Cube.exe 0x5C9B30 World_generateMonsterSpawnList / 0x5CA0A0 World_generateNpcSpawnList,
//           executed by tools/alpha_models/world/spawn_oracle.py (EMULATED_ALPHA_CODE)
//   world seeds: {seeds}
//   records: monster {agg['counts']['monster']}, npc {agg['counts']['npc']}
//   DO NOT EDIT: regenerate with `python -m tools.alpha_content.build_spawn_table`
// </auto-generated>
namespace CubeGame.Content
{{
    /// <summary>One weighted (level, kind) row of Alpha's spawn table. Weight is the value Alpha rolled for that record.</summary>
    public readonly struct AlphaSpawnEntryDef
    {{
        public readonly int Level;
        public readonly int Kind;
        public readonly int Weight;

        public AlphaSpawnEntryDef(int level, int kind, int weight)
        {{
            Level = level;
            Kind = kind;
            Weight = weight;
        }}
    }}

    /// <summary>Alpha spawn table, produced by running Alpha's own table builders.</summary>
    public static class AlphaSpawnTable
    {{
        public const string Format = "cubegame.alpha_spawn_table/1";
        public const string Status = "EMULATED_ALPHA_CODE";
        public const string Source = "Cube.exe 0x5C9B30 / 0x5CA0A0 via tools/alpha_models/world/spawn_oracle.py";
        public const string Seeds = "{seeds}";

        /// <summary>Highest level row the executed tables contain.</summary>
        public const int MaxLevel = {max_level};

        /// <summary>Monster spawn records (type 2 of the client's 0x118 descriptor).</summary>
{table('Monster', mon)}
        /// <summary>NPC spawn records (type 3 of the client's 0x118 descriptor).</summary>
{table('Npc', npc)}
        /// <summary>All kinds the executed tables contain (Alpha creature kind ids).</summary>
        public static readonly int[] Kinds = {{ {', '.join(f'0x{k:02X}' for k in kinds)} }};

        /// <summary>PARTIAL: the monster record's +0xC byte is not a star count (see the generator header).</summary>
        public const string MonsterStarsStatus = "PARTIAL: star byte semantics of the monster record is not established; stars stay 0";
    }}
}}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", default=str(INPUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    doc = json.loads(Path(a.input).read_text(encoding="utf-8"))
    if doc.get("RESULT") != "PASS":
        print(f"SPAWN_TABLE_RESULT=FAIL source RESULT={doc.get('RESULT')} problems={doc.get('problems')}")
        return 1
    text = build(doc)
    if a.check:
        drift = not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text
        print(f"SPAWN_TABLE_RESULT={'FAIL' if drift else 'PASS'} drift={drift} out={OUTPUT}")
        return 1 if drift else 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    agg = aggregate(doc)
    print(f"SPAWN_TABLE_RESULT=PASS monster_rows={len(agg['rows']['monster'])} npc_rows={len(agg['rows']['npc'])} "
          f"records={agg['counts']} out={OUTPUT.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
