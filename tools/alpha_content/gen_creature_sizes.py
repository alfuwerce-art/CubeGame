"""M0-F2B: Alpha creature size (hit box) per kind for the Unity combat runtime.

Evidence: ``.scratch/catalog/alpha_static.json`` (``tools/alpha_models/universal/alpha_static.py`` —
``kind_table``), produced by emulating ``creature_generateAppearance`` of the local ``Cube.exe`` for every
kind 0x00..0x9B. The appearance block stores the creature size at +0x08 (three floats, Alpha axes x, y, z = up).
The projectile hit test of ``GameController_updateSubsystems`` (0x621590..0x621912) compares
``|projectile - creature|`` with ``size / 2 + projectile size`` on every axis, so this is the creature's
combat box. Nothing is decided here; the script only re-encodes the emulated numbers.

Second column (M0-F2B species scale): the uniform scale of the creature placement matrix that
``Creature_drawModel`` (0x4128F0) multiplies into every part (``local_14e0``), read by executing the shipped
code in ``tools/alpha_models/universal/drawmodel_emu.py`` for every kind. The S05 pose capture divides this
placement out (``alpha_clip.joint_frame``), so Unity must re-apply ``placement(kind) / placement(0x02)``.
The run refuses a non-uniform placement or one that changes between two frame sequences.

    python -m tools.alpha_content.gen_creature_sizes
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ALPHA_STATIC = ROOT / ".scratch/catalog/alpha_static.json"
OUT = ROOT / "Assets/CubeGame/Content/Generated/AlphaCreatureSizes.g.cs"


def load_sizes(path: Path):
    data = json.loads(path.read_text(encoding="utf-8"))
    sizes = {}
    for key, entry in data["kinds"].items():
        appearance = entry.get("appearance")
        if not appearance or "size" not in appearance:
            continue
        sizes[int(key, 16)] = [float(v) for v in appearance["size"]]
    return data, sizes


def placement_scales(kinds):
    import math
    from tools.alpha_models.catalog.item_layer import ItemLayer, DEFAULT_DB
    from tools.alpha_models.universal import drawmodel_emu as de
    layer = ItemLayer(ROOT / ".scratch/alphatest2/Cube.exe", DEFAULT_DB)
    out, problems = {}, []
    for kind in kinds:
        values = []
        for frames in ((600, 600, 16), (16,)):
            em = de.Emulator(layer.image, bytes(layer.base_for(kind)), layer.sizes)
            fr = None
            for dt in frames:
                fr = em.frame(dt_ms=dt)
            P = fr["placement"]
            rows = [math.sqrt(sum(v * v for v in P[r * 4:r * 4 + 3])) for r in range(3)]
            if max(rows) - min(rows) > 1e-5:
                problems.append(f"NON_UNIFORM_PLACEMENT 0x{kind:02X} {rows}")
            values.append(rows[0])
        if abs(values[0] - values[1]) > 1e-6:
            problems.append(f"FRAME_DEPENDENT_PLACEMENT 0x{kind:02X} {values}")
        out[kind] = values[0]
    return out, problems


def render(data, sizes, scales) -> str:
    lines = [
        "// <auto-generated> tools/alpha_content/gen_creature_sizes.py — do not edit by hand.",
        f"// Source: {data['format']} exe {data['exe_sha256'][:16]}: creature_generateAppearance, appearance +0x08 (emulated).",
        "using System.Collections.Generic;",
        "",
        "namespace CubeGame.Content",
        "{",
        "    public static partial class AlphaCreatureSizes",
        "    {",
        f"        public const string Source = \"{data['format']} exe {data['exe_sha256'][:16]} appearance+0x08 (ALPHA_CODE_STATIC, emulated)\";",
        "",
        "        /// <summary>Kind → Alpha size (x, y, z = up), blocks; 4th value: uniform scale of the drawModel placement matrix.</summary>",
        "        private static readonly Dictionary<int, float[]> Sizes = new Dictionary<int, float[]>",
        "        {",
    ]
    for kind in sorted(sizes):
        x, y, z = sizes[kind]
        k = round(scales[kind], 7)
        lines.append(f"            {{ 0x{kind:02X}, new[] {{ {x!r}f, {y!r}f, {z!r}f, {k!r}f }} }},")
    lines += ["        };", "    }", "}", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--static", default=str(ALPHA_STATIC))
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    data, sizes = load_sizes(Path(args.static))
    scales, problems = placement_scales(sorted(sizes))
    if problems:
        print("CREATURE_SIZES_RESULT=FAIL", problems)
        return 1
    Path(args.out).write_text(render(data, sizes, scales), encoding="utf-8", newline="\n")
    print(f"CREATURE_SIZES_RESULT=PASS {len(sizes)} kinds -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
