"""D86 M0-06A: build the committed table of prepared (staged) Alpha visual variants.

The variants themselves live in the local content cache (``.scratch/content/actors``, never in Git);
what the game needs in the repository is the *list* of kind -> variant pairs that were actually
prepared and verified by the transfer pipeline, so the spawner can resolve them and the tests can
assert every staged kind loads. This script reads the local cache and writes that list.

    python -m tools.alpha_content.build_staged_visuals            # write
    python -m tools.alpha_content.build_staged_visuals --check    # verify no drift
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / ".scratch/content/actors"
OUT_JSON = ROOT / "tools/alpha_content/data/staged_visuals.json"
OUT_CS = ROOT / "Assets/CubeGame/Content/Generated/AlphaStagedVisuals.g.cs"


def cs(value: str) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def collect() -> list[dict]:
    if not CACHE.is_dir():
        raise SystemExit(f"STAGED_VISUALS=FAIL cache missing {CACHE} (run stage_local_content first)")
    rows = []
    for actor_dir in sorted(p for p in CACHE.iterdir() if p.is_dir()):
        rig_path = actor_dir / "rig.json"
        if not rig_path.exists():
            continue
        rig = json.loads(rig_path.read_text(encoding="utf-8"))
        kind = rig.get("kind")
        if kind is None:
            raise SystemExit(f"STAGED_VISUALS=FAIL no kind in {rig_path}")
        contract = {}
        contract_path = actor_dir / "contract.json"
        if contract_path.exists():
            contract = json.loads(contract_path.read_text(encoding="utf-8"))
        clips = len(list((actor_dir / "clips").glob("*.json")))
        rows.append({
            "kind": int(kind),
            "variant": rig.get("variant") or actor_dir.name,
            "mode": contract.get("controllerMode", "UNKNOWN"),
            "parts": len(rig.get("parts", [])),
            "clips": clips,
            "rig": rig.get("rig", ""),
        })
    rows.sort(key=lambda r: (r["kind"], r["variant"]))
    return rows


def build(rows: list[dict]) -> str:
    lines = ["// <auto-generated>",
             "// Generated by tools/alpha_content/build_staged_visuals.py from the local content cache.",
             "// The variants themselves stay outside Git; this file only lists prepared kind -> variant pairs.",
             f"// entries={len(rows)}",
             "// </auto-generated>",
             "namespace CubeGame.Content",
             "{",
             "    /// <summary>One prepared Alpha visual variant (kind -> local cache variant).</summary>",
             "    public readonly struct AlphaStagedVisualDef",
             "    {",
             "        public readonly int Kind; public readonly string Variant; public readonly string ControllerMode;",
             "        public readonly int Parts; public readonly int Clips; public readonly string Rig;",
             "        public AlphaStagedVisualDef(int kind, string variant, string mode, int parts, int clips, string rig)",
             "        { Kind = kind; Variant = variant; ControllerMode = mode; Parts = parts; Clips = clips; Rig = rig; }",
             "    }",
             "",
             "    /// <summary>Prepared visual variants of the Alpha catalog (ids only; data lives in the local cache).</summary>",
             "    public static class AlphaStagedVisuals",
             "    {",
             '        public const string Format = "cubegame.staged_visuals/1";',
             "",
             "        public static readonly AlphaStagedVisualDef[] All =",
             "        {",
             ]
    for r in rows:
        lines.append("            new AlphaStagedVisualDef(" + str(r["kind"]) + ", " + cs(r["variant"]) + ", " +
                     cs(r["mode"]) + ", " + str(r["parts"]) + ", " + str(r["clips"]) + ", " + cs(r["rig"]) + "),")
    lines += ["        };", "    }", "}"]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    rows = collect()
    text = build(rows)
    payload = json.dumps({"format": "cubegame.staged_visuals/1", "entries": rows}, indent=1, ensure_ascii=True) + "\n"
    if a.check:
        ok = OUT_JSON.exists() and OUT_CS.exists()
        if ok:
            ok = OUT_JSON.read_text(encoding="utf-8") == payload and OUT_CS.read_text(encoding="utf-8") == text
        print(("STAGED_VISUALS=PASS" if ok else "STAGED_VISUALS=FAIL drift") + f" entries={len(rows)}")
        return 0 if ok else 1
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_CS.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(payload, encoding="utf-8", newline="\n")
    OUT_CS.write_text(text, encoding="utf-8", newline="\n")
    kinds = sorted({r["kind"] for r in rows})
    print(f"STAGED_VISUALS=PASS entries={len(rows)} kinds={len(kinds)} out={OUT_CS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
