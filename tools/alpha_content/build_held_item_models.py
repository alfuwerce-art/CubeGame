"""D86 M0-04B: distill the item -> model mapping from the executed item_icon_id sweep.

The sweep (``tools/alpha_models/catalog/item_models.py``) executes ``item_icon_id`` @ 0x004EC400 over
the item domains and resolves every selected model index through the Alpha model registry. Its raw
output is a large local file; the game only needs the ids/names of the items whose model is a *held*
visual (consumables, lantern, hang glider, boat). This script writes that distilled list.

    python -m tools.alpha_models.catalog.item_models --out .scratch/tmp/item_models_full.json
    python -m tools.alpha_content.build_held_item_models --raw .scratch/tmp/item_models_full.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_JSON = ROOT / "tools/alpha_content/data/held_item_models.json"
OUT_CS = ROOT / "Assets/CubeGame/Content/Generated/AlphaHeldItemModels.g.cs"
SELECTOR_VA = "0x004EC400"
# Item types whose model is drawn as a held/attached object (not armour worn on a body part).
TYPES = {1: "consumable", 23: "hangGliderAndBoat", 24: "lamp"}


def cs(value: str) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--raw", default=str(ROOT / ".scratch/tmp/item_models_full.json"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    raw_path = Path(a.raw)
    if not raw_path.exists():
        print("HELD_ITEM_MODELS=FAIL raw sweep missing " + str(raw_path))
        return 1
    sweep = json.loads(raw_path.read_text(encoding="utf-8"))
    models = sweep["models"]
    rows = []
    for type_id, label in TYPES.items():
        info = sweep["types"].get(str(type_id)) or {}
        for selector in info.get("selectors", []):
            when = selector.get("when") or []
            if not when:
                continue
            first = when[0]
            subtypes = first.get("subtype")
            if subtypes and (not isinstance(subtypes, list) or len(subtypes) != 1):
                continue
            subtype = int(subtypes[0]) if subtypes else -1
            model_ids = [m for m in selector.get("models", []) if m is not None]
            if len(model_ids) != 1:
                continue
            model = models.get(str(model_ids[0])) or {}
            name = model.get("name")
            if not name:
                continue
            rows.append({
                "type": type_id,
                "subtype": subtype,
                "label": label,
                "model": name,
                "modelIndex": model_ids[0],
            })
    rows.sort(key=lambda r: (r["type"], r["subtype"]))
    payload = {
        "format": "cubegame.held_item_models/1",
        "status": "EMULATED_ALPHA_CODE: models selected by executing item_icon_id; placements are the held block law",
        "source": {
            "selector": SELECTOR_VA,
            "tool": "tools/alpha_models/catalog/item_models.py",
            "sweep_sha256": hashlib.sha256(raw_path.read_bytes()).hexdigest(),
            "note": "distilled ids/names/model files only; geometry stays in the local cache",
        },
        "items": rows,
    }
    text = json.dumps(payload, indent=1, ensure_ascii=True) + "\n"
    if a.check:
        ok = OUT_JSON.exists() and OUT_JSON.read_text(encoding="utf-8") == text
        print(("HELD_ITEM_MODELS=PASS" if ok else "HELD_ITEM_MODELS=FAIL drift") + f" items={len(rows)}")
        return 0 if ok else 1
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(text, encoding="utf-8", newline="\n")
    lines = [
        "// <auto-generated>",
        "// Generated by tools/alpha_content/build_held_item_models.py from the executed",
        f"// item_icon_id ({SELECTOR_VA}) sweep. Geometry stays in the local cache.",
        f"// items={len(rows)}", "// </auto-generated>",
        "namespace CubeGame.Content", "{",
        "    /// <summary>One item whose model is a held/attached visual (D86 M0-04B).</summary>",
        "    public readonly struct AlphaHeldItemDef",
        "    {",
        "        public readonly int Type, Subtype, ModelIndex; public readonly string Label, Model;",
        "        public AlphaHeldItemDef(int type, int subtype, int modelIndex, string label, string model)",
        "        { Type = type; Subtype = subtype; ModelIndex = modelIndex; Label = label; Model = model; }",
        "    }",
        "",
        "    public static class AlphaHeldItemModels",
        "    {",
        '        public const string Format = "cubegame.held_item_models/1";',
        f'        public const string Selector = "{SELECTOR_VA}";',
        "",
        "        public static readonly AlphaHeldItemDef[] Items =",
        "        {",
    ]
    for r in rows:
        lines.append(f"            new AlphaHeldItemDef({r['type']}, {r['subtype']}, {r['modelIndex']}, "
                     f"{cs(r['label'])}, {cs(r['model'])}),")
    lines += ["        };", "    }", "}"]
    OUT_CS.parent.mkdir(parents=True, exist_ok=True)
    OUT_CS.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"HELD_ITEM_MODELS=PASS items={len(rows)} out={OUT_CS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
