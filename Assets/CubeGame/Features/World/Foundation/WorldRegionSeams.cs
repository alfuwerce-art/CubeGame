// CubeGame.Features.World.Foundation — G2-G: city / dungeon seams.
//
// This is not a city generator and not a dungeon generator. It is the contract the future ones will use:
//
//   * a settlement RESERVES a site (one zone, radius, biome, level) plus its NPC anchor points and its road
//     connection stubs, all with stable persistent ids;
//   * a dungeon entrance belongs to a zone, points at a dungeon instance id (a region the dungeon generator will
//     occupy), and carries level/stars so the runtime can seed the instance deterministically;
//   * both are pure functions of (seed, region/zone) and the world facts, so they survive unload/reload and save.
//
// The city generator (G5/G11) will receive a SettlementSite and fill it; the dungeon generator will receive a
// DungeonEntranceSite and build the instance. Roads are stubs here: the world's road pass, when it exists, connects
// the stubs; nothing is drawn or carved by this file.
using System;
using System.Collections.Generic;
using System.Globalization;
using CubeGame.Content;
using CubeGame.Core.Generation;
using CubeGame.Features.Contracts;

namespace CubeGame.Features.World.Foundation
{
    /// <summary>Anchor kinds a settlement publishes to the population layer.</summary>
    public enum WorldAnchorKind
    {
        SettlementCenter = 0,
        Inn = 1,
        Shop = 2,
        Smith = 3,
        QuestGiver = 4,
        Guard = 5,
        Villager = 6,
        DungeonEntrance = 7,
        CampCenter = 8,
        LandmarkCenter = 9,
    }

    public sealed class NpcAnchorSpec
    {
        public WorldAnchorKind Kind;
        public int Index;
        public int X;
        public int Z;
        public int SurfaceY;
        public string PersistentId = string.Empty;

        public override string ToString() => $"{Kind}#{Index} ({X},{SurfaceY},{Z}) {PersistentId}";
    }

    /// <summary>Stub where a road leaves a settlement. Direction: 0 = −Z, 1 = +X, 2 = +Z, 3 = −X.</summary>
    public sealed class RoadConnectionPoint
    {
        public int Index;
        public int Direction;
        public int X;
        public int Z;
        public int SurfaceY;
        public string PersistentId = string.Empty;

        public override string ToString() => $"road#{Index} dir={Direction} ({X},{Z}) {PersistentId}";
    }

    /// <summary>A reserved place for a city/village. The generator that fills it is a later stage.</summary>
    public sealed class SettlementSite
    {
        public string PersistentId = string.Empty;
        public int RegionX;
        public int RegionZ;
        public int ZoneX;
        public int ZoneZ;
        public int CenterX;
        public int CenterZ;
        public int SurfaceY;
        public string BiomeId = string.Empty;
        public int Level;
        public int RadiusVoxels = 48;
        public string State = "reserved";
        public string Status = "CUBEGAME_CONTRACT: site reserved; geometry not built (G2-G)";
        public readonly List<NpcAnchorSpec> Anchors = new List<NpcAnchorSpec>();
        public readonly List<RoadConnectionPoint> Roads = new List<RoadConnectionPoint>();

        public override string ToString() =>
            $"{PersistentId} zone=({ZoneX},{ZoneZ}) centre=({CenterX},{CenterZ}) biome={BiomeId} level={Level} " +
            $"anchors={Anchors.Count} roads={Roads.Count} {State}";
    }

    /// <summary>Entrance of a dungeon instance. The instance itself is generated by G11.</summary>
    public sealed class DungeonEntranceSite
    {
        public string PersistentId = string.Empty;
        public int ZoneX;
        public int ZoneZ;
        public int X;
        public int Y;
        public int Z;
        public int DungeonRegionX;
        public int DungeonRegionZ;
        public string DungeonInstanceId = string.Empty;
        public string BiomeId = string.Empty;
        public int Level = 1;
        public int Stars;
        public string State = "reserved";
        public string Status = "CUBEGAME_CONTRACT: entrance seam; instance generated by G11";

        public override string ToString() =>
            $"{PersistentId} zone=({ZoneX},{ZoneZ}) at ({X},{Y},{Z}) instance={DungeonInstanceId} lvl={Level} " +
            $"stars={Stars} {BiomeId} {State}";
    }

    /// <summary>Read-only world facts for the seam planners.</summary>
    public interface IWorldSeamProbe
    {
        string BiomeOf(int x, int z);

        int SurfaceAt(int x, int z);

        int RegionLevel(int regionX, int regionZ);
    }

    /// <summary>Persistent ids of every seam object. Parsed back by the save/debug layer.</summary>
    public static class WorldSeamIds
    {
        public const string SettlementPrefix = "seam.settlement";
        public const string AnchorPrefix = "seam.anchor";
        public const string RoadPrefix = "seam.road";
        public const string DungeonPrefix = "seam.dungeon";

        public static string Settlement(uint seed, int regionX, int regionZ) =>
            $"{SettlementPrefix}:{seed.ToString(CultureInfo.InvariantCulture)}:" +
            $"{regionX.ToString(CultureInfo.InvariantCulture)}:{regionZ.ToString(CultureInfo.InvariantCulture)}";

        public static string Anchor(uint seed, int regionX, int regionZ, WorldAnchorKind kind, int index) =>
            $"{AnchorPrefix}:{seed.ToString(CultureInfo.InvariantCulture)}:" +
            $"{regionX.ToString(CultureInfo.InvariantCulture)}:{regionZ.ToString(CultureInfo.InvariantCulture)}:" +
            $"{(int)kind}:{index.ToString(CultureInfo.InvariantCulture)}";

        public static string Road(uint seed, int regionX, int regionZ, int index) =>
            $"{RoadPrefix}:{seed.ToString(CultureInfo.InvariantCulture)}:" +
            $"{regionX.ToString(CultureInfo.InvariantCulture)}:{regionZ.ToString(CultureInfo.InvariantCulture)}:" +
            index.ToString(CultureInfo.InvariantCulture);

        public static string Dungeon(uint seed, int zoneX, int zoneZ) =>
            $"{DungeonPrefix}:{seed.ToString(CultureInfo.InvariantCulture)}:" +
            $"{zoneX.ToString(CultureInfo.InvariantCulture)}:{zoneZ.ToString(CultureInfo.InvariantCulture)}";

        public static string DungeonInstance(uint seed, int regionX, int regionZ) =>
            $"dungeon.instance:{seed.ToString(CultureInfo.InvariantCulture)}:" +
            $"{regionX.ToString(CultureInfo.InvariantCulture)}:{regionZ.ToString(CultureInfo.InvariantCulture)}";

        public static bool IsSettlement(string id) => HasPrefix(id, SettlementPrefix);

        public static bool IsAnchor(string id) => HasPrefix(id, AnchorPrefix);

        public static bool IsRoad(string id) => HasPrefix(id, RoadPrefix);

        public static bool IsDungeon(string id) => HasPrefix(id, DungeonPrefix);

        private static bool HasPrefix(string id, string prefix) =>
            !string.IsNullOrEmpty(id) && id.StartsWith(prefix + ":", StringComparison.Ordinal);
    }

    /// <summary>Reserves settlement sites. One deterministic candidate per region; nothing is forced on bad terrain.</summary>
    public static class SettlementSeamPlanner
    {
        public const string Provenance = "CUBEGAME_CONTRACT: settlement seams only (G2-G); city generator is G5/G11";

        public const int MinLevel = 1;
        public const int MaxLevel = 6;

        /// <summary>
        /// Plans the settlement of one region, or null when the region must stay empty. The same region and seed always
        /// produce the same site (or the same "no"), including anchor and road ids.
        /// </summary>
        public static SettlementSite Plan(uint worldSeed, int regionX, int regionZ, IWorldSeamProbe probe,
            StructureRuleSet rules = null, List<string> problems = null)
        {
            if (probe == null)
            {
                problems?.Add("SEAM_PROBE_MISSING");
                return null;
            }

            var region = new RegionKey(regionX, regionZ);
            if (!WorldLayout.IsInside(region))
            {
                problems?.Add($"SEAM_REGION_OUTSIDE_WORLD {region}");
                return null;
            }

            int level = probe.RegionLevel(regionX, regionZ);
            if (level < MinLevel || level > MaxLevel) return null;

            uint hash = DeterministicHash.Combine(unchecked((int)worldSeed), regionX, regionZ, 0x5E77, 1);
            int localX = (int)((hash >> 3) % (uint)WorldLayout.ZonesPerRegion);
            int localZ = (int)((hash >> 17) % (uint)WorldLayout.ZonesPerRegion);
            int zoneX = regionX * WorldLayout.ZonesPerRegion + localX;
            int zoneZ = regionZ * WorldLayout.ZonesPerRegion + localZ;
            int centerX = zoneX * WorldLayout.ZoneSize + WorldLayout.ZoneSize / 2;
            int centerZ = zoneZ * WorldLayout.ZoneSize + WorldLayout.ZoneSize / 2;
            string biome = probe.BiomeOf(centerX, centerZ);
            int surface = probe.SurfaceAt(centerX, centerZ);
            if (surface <= int.MinValue / 4)
            {
                problems?.Add($"SEAM_NO_SURFACE {centerX}:{centerZ}");
                return null;
            }

            if (rules != null && rules.TryGet("structure.village", out StructureRule village) &&
                !village.AllowsBiome(biome))
            {
                return null;
            }

            var site = new SettlementSite
            {
                PersistentId = WorldSeamIds.Settlement(worldSeed, regionX, regionZ),
                RegionX = regionX,
                RegionZ = regionZ,
                ZoneX = zoneX,
                ZoneZ = zoneZ,
                CenterX = centerX,
                CenterZ = centerZ,
                SurfaceY = surface,
                BiomeId = biome,
                Level = level,
            };

            // Anchors: one centre plus the services the population layer needs. Offsets are CubeGame layout data.
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.SettlementCenter, 0, 0, 0);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.Inn, 0, 12, 0);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.Shop, 0, 0, 12);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.Shop, 1, 0, -12);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.Smith, 0, -12, 0);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.QuestGiver, 0, 8, 8);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.Guard, 0, -8, 8);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.Villager, 0, 8, -8);
            AddAnchor(site, probe, worldSeed, WorldAnchorKind.Villager, 1, -8, -8);

            for (int direction = 0; direction < 4; direction++)
            {
                int dx = direction == 1 ? 1 : (direction == 3 ? -1 : 0);
                int dz = direction == 0 ? -1 : (direction == 2 ? 1 : 0);
                int x = centerX + dx * site.RadiusVoxels;
                int z = centerZ + dz * site.RadiusVoxels;
                site.Roads.Add(new RoadConnectionPoint
                {
                    Index = direction,
                    Direction = direction,
                    X = x,
                    Z = z,
                    SurfaceY = probe.SurfaceAt(x, z),
                    PersistentId = WorldSeamIds.Road(worldSeed, regionX, regionZ, direction),
                });
            }

            return site;
        }

        private static void AddAnchor(SettlementSite site, IWorldSeamProbe probe, uint seed, WorldAnchorKind kind,
            int index, int offsetX, int offsetZ)
        {
            int x = site.CenterX + offsetX;
            int z = site.CenterZ + offsetZ;
            site.Anchors.Add(new NpcAnchorSpec
            {
                Kind = kind,
                Index = index,
                X = x,
                Z = z,
                SurfaceY = probe.SurfaceAt(x, z),
                PersistentId = WorldSeamIds.Anchor(seed, site.RegionX, site.RegionZ, kind, index),
            });
        }
    }

    /// <summary>Reserves dungeon entrance sites. One candidate per 2×2 region block, deterministic.</summary>
    public static class DungeonSeamPlanner
    {
        public const string Provenance = "CUBEGAME_CONTRACT: dungeon entrance seams (G2-G); instance generator is G11";

        public const int RegionsPerBlock = 2;

        public static DungeonEntranceSite Plan(uint worldSeed, int zoneX, int zoneZ, IWorldSeamProbe probe,
            List<string> problems = null)
        {
            if (probe == null)
            {
                problems?.Add("SEAM_PROBE_MISSING");
                return null;
            }

            var zone = new WorldZoneKey(zoneX, zoneZ);
            if (!AlphaWorldScale.IsInsideWorld(zone))
            {
                problems?.Add($"SEAM_ZONE_OUTSIDE_WORLD {zone}");
                return null;
            }

            int blockX = AlphaWorldScale.RegionOfZone(zoneX) / RegionsPerBlock;
            int blockZ = AlphaWorldScale.RegionOfZone(zoneZ) / RegionsPerBlock;
            uint hash = DeterministicHash.Combine(unchecked((int)worldSeed), blockX, blockZ, 0xD067, 1);
            int level = 1 + (int)((hash >> 5) % 12u);
            int stars = 1 + (int)((hash >> 13) % 5u);
            int centerX = zoneX * WorldLayout.ZoneSize + WorldLayout.ZoneSize / 2;
            int centerZ = zoneZ * WorldLayout.ZoneSize + WorldLayout.ZoneSize / 2;
            int surface = probe.SurfaceAt(centerX, centerZ);
            if (surface <= int.MinValue / 4)
            {
                problems?.Add($"SEAM_NO_SURFACE {centerX}:{centerZ}");
                return null;
            }

            return new DungeonEntranceSite
            {
                PersistentId = WorldSeamIds.Dungeon(worldSeed, zoneX, zoneZ),
                ZoneX = zoneX,
                ZoneZ = zoneZ,
                X = centerX,
                Y = surface + 1,
                Z = centerZ,
                DungeonRegionX = blockX * RegionsPerBlock,
                DungeonRegionZ = blockZ * RegionsPerBlock,
                DungeonInstanceId = WorldSeamIds.DungeonInstance(worldSeed, blockX, blockZ),
                BiomeId = probe.BiomeOf(centerX, centerZ),
                Level = level,
                Stars = stars,
            };
        }

        /// <summary>One dungeon block owns exactly one entrance zone; this answers whether (zoneX, zoneZ) is it.</summary>
        public static bool IsEntranceZone(int zoneX, int zoneZ, int worldSeed, int blockX, int blockZ)
        {
            int span = RegionsPerBlock * WorldLayout.ZonesPerRegion;
            uint hashX = DeterministicHash.Combine(worldSeed, blockX, blockZ, 0xD067, 1);
            uint hashZ = DeterministicHash.Combine(worldSeed, blockX, blockZ, 0xD068, 2);
            int slotX = blockX * span + (int)(hashX % (uint)span);
            int slotZ = blockZ * span + (int)(hashZ % (uint)span);
            return zoneX == slotX && zoneZ == slotZ;
        }
    }

    /// <summary>World-backed seam probe: climate biome, generated surface, region level.</summary>
    public sealed class WorldSeamProbe : IWorldSeamProbe
    {
        private readonly IWorldClimateSource _climate;
        private readonly Func<int, int, int> _surfaceAt;
        private readonly BiomeCatalog _biomes;

        public WorldSeamProbe(IWorldClimateSource climate, Func<int, int, int> surfaceAt, BiomeCatalog biomes)
        {
            _climate = climate ?? throw new ArgumentNullException(nameof(climate));
            _surfaceAt = surfaceAt ?? throw new ArgumentNullException(nameof(surfaceAt));
            _biomes = biomes;
        }

        public string BiomeOf(int x, int z) => _biomes?.Resolve(_climate.Sample(x, z))?.Id ?? string.Empty;

        public int SurfaceAt(int x, int z) => _surfaceAt(x, z);

        public int RegionLevel(int regionX, int regionZ) => AlphaTerrainGenerator.Level(regionX, regionZ);
    }
